# ===== 商品名クリーニング =====
# 楽天の商品名に付きがちな販促ノイズ。ブラケット単位 / 単語単位で除去する
_PROMO_BLOCK = (
    r"期間限定|数量限定|限定販売|数量限定|送料無料|送料込|送料別|ポイント|P\d?倍|\d+倍|"
    r"OFF|オフ|クーポン|セール|SALE|特価|激安|格安|お得|キャンペーン|ランキング|"
    r"\d+位|第\d+位|還元|当店|全品|税込|税抜|即出荷|即日出荷|当日出荷|レビュー|"
    r"プレゼント|セット割|まとめ買い|訳あり|新作|人気|話題|公式|正規品|楽天|"
    r"\d{1,2}/\d{1,2}\s*\d{1,2}:\d{2}\s*[~〜－-]"
)
NOISE_PATTERNS = [
    re.compile(r"【[^】]{0,80}?(?:" + _PROMO_BLOCK + r")[^】]{0,80}?】", re.I),
    re.compile(r"\[[^\]]{0,80}?(?:" + _PROMO_BLOCK + r")[^\]]{0,80}?\]", re.I),
    re.compile(r"[（(][^)）]{0,60}?(?:" + _PROMO_BLOCK + r")[^)）]{0,60}?[)）]", re.I),
    re.compile(r"＼[^＼]{0,40}?(?:ポイント|OFF|還元|お得|限定)[^＼]{0,40}?＼", re.I),
    re.compile(r"★\s*\d+\s*倍|P\s*\d+\s*倍", re.I),
    re.compile(r"ポイント(?:最大)?\s*\d+\s*倍(?:以上)?", re.I),
    re.compile(r"(?:MAX\s*)?\d+(?:\.\d+)?\s*[％%]\s*(?:OFF|オフ)|\d+\s*円\s*(?:OFF|オフ)", re.I),
    re.compile(r"\d{1,2}/\d{1,2}\s*\d{1,2}:\d{2}\s*[~〜－-]\s*\d{1,2}/\d{1,2}\s*\d{1,2}:\d{2}"),
    re.compile(r"(?:楽天市場?)\s*(?:ランキング)?\s*第?\s*\d+\s*位"),
    re.compile(r"[＼\\/][^＼\\/]{0,40}?(?:ポイント|OFF|還元|お得|限定)[^＼\\/]{0,40}?[＼\\/]", re.I),
    re.compile(r"\d+\s*[％%]?\s*ポイント(?:還元|バック)|ポイント(?:最大)?\s*\d+\s*倍(?:以上)?", re.I),
    re.compile(r"期間限定|数量限定|送料無料|送料込|クーポン|セール|SALE|特価|激安|格安|キャンペーン|当店|全品|税込|税抜|即日出荷|当日出荷|楽天市場|公式|正規品", re.I),
    re.compile(r"^(?:【[^】]*】|\[[^\]]*\])(?=\S)"),
    re.compile(r"^[＼\\/｜|・★☆\s]+|[＼/｜|・\s]+$"),
]


def clean_product_name(name, limit=None):
    """楽天タイトルから販促ノイズを落とし、ブランド・商品名を先頭に見せる。

    >>> clean_product_name("【期間限定★P10倍】化粧水 敏感肌 150ml 送料無料")
    '化粧水 敏感肌 150ml'
    """
    s = str(name or "")
    for pat in NOISE_PATTERNS:
        s = pat.sub(" ", s)
    # 残った【】は型番・容量などの情報なので中身だけ残す
    s = s.replace("【", " ").replace("】", " ")
    s = re.sub(r"\s+", " ", s).strip(" 　-–—/|｜・／＼")
    s = re.sub(r"([☆★])\1{2,}", r"\1\1", s)
    if limit and len(s) > limit:
        s = s[:limit].rstrip(" 　、。") + "…"
    return s


